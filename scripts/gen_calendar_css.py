"""Generate app/web/static/calendar.css.

The CSP forbids inline style="", so grid positions of calendar entries are expressed as classes:
gc<col> / gr<row> / gs<span> and lane-<i>-<n>. Re-run after changing the limits below.
"""
from pathlib import Path

MAX_ROWS = 49   # 24h in 30-min rows + header
MAX_SPAN = 48
MAX_LANES = 4

lines = ["/* GENERATED by scripts/gen_calendar_css.py - do not edit by hand */"]
lines += [f".gc{c}{{grid-column:{c}}}" for c in range(2, 9)]
lines += [f".gr{r}{{grid-row-start:{r}}}" for r in range(2, MAX_ROWS + 2)]
lines += [f".gs{s}{{grid-row-end:span {s}}}" for s in range(1, MAX_SPAN + 1)]
for n in range(1, MAX_LANES + 1):
    for i in range(n):
        lines.append(f".lane-{i}-{n}{{width:calc({100 / n:.4f}% - 2px);margin-left:calc({100 * i / n:.4f}% + 1px)}}")
lines += [f".tr{r}{{grid-row:{r}}}" for r in range(2, MAX_ROWS + 2)]
# explicit rows, so that "grid-row: 2 / -1" (day columns) really spans every time row and not the header
lines += [f".rows-{n}{{grid-template-rows:34px repeat({n},26px)}}" for n in range(1, MAX_SPAN + 1)]
Path("app/web/static/calendar.css").write_text("\n".join(lines) + "\n", encoding="utf-8")
print(len(lines), "rules")
